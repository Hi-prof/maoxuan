def _load_existing() -> list[dict[str, Any]]:
    records = []
    for path in sorted(CARDS_DIR.glob("*.yaml")):
        if path.name[:3].isdigit() and int(path.name[:3]) >= 32:
            continue
        record = yaml.safe_load(path.read_text(encoding="utf-8"))
        if record.get("status") == "published":
            records.append(record)
    return records


def _validate_entries(existing: list[dict[str, Any]]) -> None:
    numbers = [entry[0] for entry in ENTRIES]
    quotes = [entry[2] for entry in ENTRIES]
    if numbers != list(range(32, 151)):
        raise ValueError("entries must use every number from 032 through 150 exactly once")
    if len(ENTRIES) != 119 or sum(number <= 120 for number in numbers) != 89:
        raise ValueError("entries must contain exactly 89 prose and 30 poetry cards")
    if len(set(quotes)) != len(quotes):
        raise ValueError("new card quotes must be unique")
    existing_quotes = {str(record["quote"]) for record in existing}
    overlap = sorted(existing_quotes & set(quotes))
    if overlap:
        raise ValueError(f"new quotes duplicate existing cards: {overlap}")
    oversized = [(number, len(quote)) for number, _, quote, *_ in ENTRIES if len(quote) > 90]
    if oversized:
        raise ValueError(f"quotes exceed 90 code points: {oversized}")

    work_counts = Counter(
        str(record["literature"]["workTitle"]) for record in existing
    )
    work_counts.update(WORKS[entry[3]]["title"] for entry in ENTRIES)
    major_titles = {work["title"] for work in WORKS.values() if work["major"]}
    violations = {
        title: count
        for title, count in work_counts.items()
        if count > (5 if title in major_titles else 3)
    }
    if violations:
        raise ValueError(f"work title limits exceeded: {violations}")


def _interpretation(number: int, work: dict[str, Any], meaning: str) -> str:
    templates = (
        (
            "原文出自《{title}》，围绕{scope}展开。这句话强调{meaning}。"
            "它有明确的历史对象和论述边界，今天可以借鉴其中的判断方法，但不应脱离全文把它变成适用于任何场景的口号。"
        ),
        (
            "在《{title}》讨论{scope}的语境中，这句话把重点放在{meaning}。"
            "理解它需要同时看到当时的任务和条件；用于今天时，应保留这种具体分析意识，而不是只取一句表面的豪迈表达。"
        ),
        (
            "《{title}》写到{scope}时，用这句话说明{meaning}。"
            "它的价值在于把立场转成可分析的关系和行动要求。现代阅读可以获得启发，但不能抹去作品所处的革命和建设语境。"
        ),
        (
            "这句话来自《{title}》，原文关注{scope}，核心是{meaning}。"
            "名句流传很广，准确理解仍要回到上下文：既看到它提供的精神力量，也看到成立所需的事实、组织和历史条件。"
        ),
    )
    return templates[number % len(templates)].format(
        title=work["title"], scope=work["scope"], meaning=meaning
    )


def _story(number: int, work: dict[str, Any], meaning: str) -> str:
    if work["series"] == "毛泽东诗词":
        return (
            f"《{work['title']}》以景物、行动和历史联想组织诗意。"
            f"这一句集中呈现{meaning}，既有鲜明画面，也保留了作品写作时的现实背景。"
        )
    return (
        f"《{work['title']}》围绕{work['scope']}逐层展开。"
        f"这句话把{meaning}凝练成便于记忆的表达，适合联系全文前后的论证一起阅读。"
    )


def _card_payload(entry: tuple[int, str, str, str, str, str, str]) -> dict[str, Any]:
    number, slug, quote, work_key, theme, meaning, action = entry
    work = WORKS[work_key]
    if work["series"] == "毛泽东诗词":
        sources = [
            {
                "name": "中央党史和文献研究院毛泽东诗词引用文章",
                "url": work["source"],
                "accessedAt": ACCESSED_AT,
                "type": "authoritative",
            },
            {
                "name": "共产党员网毛泽东诗词专题",
                "url": work["cross"],
                "accessedAt": ACCESSED_AT,
                "type": "contextual",
            },
        ]
    else:
        sources = [
            {
                "name": f"中文马克思主义文库《{work['title']}》全文",
                "url": work["source"],
                "accessedAt": ACCESSED_AT,
                "type": "original",
            },
            {
                "name": f"共产党员网《毛泽东选集（{work['volume']}）》",
                "url": work["cross"],
                "accessedAt": ACCESSED_AT,
                "type": "authoritative",
            },
        ]
    return {
        "id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"xinghuo-card-1.4.0:{number}:{slug}")),
        "revision": 1,
        "status": "published",
        "quote": quote,
        "literature": {
            "series": work["series"],
            "volume": work["volume"],
            "workTitle": work["title"],
            "authoredAt": work["authoredAt"],
        },
        "themes": [theme],
        "interpretation": {
            "inspiration": action,
            "explanation": _interpretation(number, work, meaning),
        },
        "historicalEvent": work["event"],
        "background": f"{work['background']} 此卡所选名句着重表现{meaning}。",
        "story": _story(number, work, meaning),
        "imageId": IMAGES[(number - 32) % len(IMAGES)],
        "sources": sources,
        "review": {"status": "verified", "checkedAt": ACCESSED_AT},
    }


def _popularity_url(number: int, work: dict[str, Any]) -> str:
    if number in POPULAR_X_NUMBERS:
        return POPULAR_XINHUA
    if number in POPULAR_H_NUMBERS:
        return POPULAR_HEBEI
    if work["series"] == "毛泽东诗词":
        return POETRY_AUTHORITY
    return work["cross"]


