def main() -> None:
    existing = _load_existing()
    _validate_entries(existing)
    expected_files = {f"{entry[0]:03d}-{entry[1]}.yaml" for entry in ENTRIES}
    unexpected_files = sorted(
        path.name
        for path in CARDS_DIR.glob("*.yaml")
        if path.name[:3].isdigit()
        and int(path.name[:3]) >= 32
        and path.name not in expected_files
    )
    if unexpected_files:
        raise ValueError(f"unexpected generated card files: {unexpected_files}")
    for entry in ENTRIES:
        number, slug, *_ = entry
        path = CARDS_DIR / f"{number:03d}-{slug}.yaml"
        path.write_text(
            yaml.safe_dump(
                _card_payload(entry),
                allow_unicode=True,
                sort_keys=False,
                width=1000,
            ),
            encoding="utf-8",
        )
    _write_catalog()
    print(
        {
            "existing": len(existing),
            "generated": len(ENTRIES),
            "prose": sum(entry[0] <= 120 for entry in ENTRIES),
            "poetry": sum(entry[0] >= 121 for entry in ENTRIES),
        }
    )


if __name__ == "__main__":
    main()
